-- ELUM Write on Supabase.
--
-- Everything the app needs: profiles, documents, sharing, comments and image
-- storage, with row level security enforcing the same rules as docs/API.md:
--   viewer < commenter < editor < owner
--   - viewers read; commenters also comment; editors also edit and share; owners also delete
--   - commenters may save a document only to add or remove comment anchors
--   - saves carry the version they started from, so concurrent edits never overwrite silently
--
-- Run it once in the Supabase SQL editor, or with `supabase db push`.

-- ---------------------------------------------------------------- profiles

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  email text not null,
  color text not null default '#f59a52',
  -- Set once the welcome document has been created for this person.
  welcomed boolean not null default false,
  created_at timestamptz not null default now()
);

create index profiles_email_lower_idx on public.profiles (lower(email));

-- Every new account gets a profile. The name comes from sign-up metadata.
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  colors text[] := array['#f59a52', '#3fc4a0', '#9b84ee', '#ec7fa9', '#e9b949', '#7093f8'];
begin
  insert into public.profiles (id, name, email, color)
  values (
    new.id,
    left(coalesce(nullif(btrim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1)), 80),
    new.email,
    colors[1 + floor(random() * array_length(colors, 1))::int]
  );
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Keep the profile email in step when someone changes it.
create function public.handle_user_email_change() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.profiles set email = new.email where id = new.id;
  return new;
end $$;

create trigger on_auth_user_email_changed
  after update of email on auth.users
  for each row when (old.email is distinct from new.email)
  execute function public.handle_user_email_change();

-- --------------------------------------------------------------- documents

create table public.documents (
  id uuid primary key default gen_random_uuid(),
  title text not null default 'Untitled document' check (char_length(title) between 1 and 200),
  owner_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  content jsonb not null default '{"type": "doc", "content": [{"type": "paragraph"}]}',
  -- A short outline of the first blocks, for thumbnails. Written by the app.
  preview jsonb not null default '[]',
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid default auth.uid() references public.profiles (id) on delete set null
);

create index documents_owner_idx on public.documents (owner_id);

create table public.document_shares (
  doc_id uuid not null references public.documents (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  role text not null check (role in ('viewer', 'commenter', 'editor')),
  added_at timestamptz not null default now(),
  added_by uuid default auth.uid() references public.profiles (id) on delete set null,
  primary key (doc_id, user_id)
);

create index document_shares_user_idx on public.document_shares (user_id);

-- When each person last opened each document, for "Last opened by me".
create table public.document_opens (
  doc_id uuid not null references public.documents (id) on delete cascade,
  user_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  opened_at timestamptz not null default now(),
  primary key (doc_id, user_id)
);

-- ---------------------------------------------------------------- comments

create table public.comments (
  -- Generated by the app, because it places the anchor in the document.
  id text primary key check (id ~ '^[A-Za-z0-9_-]{8,64}$'),
  doc_id uuid not null references public.documents (id) on delete cascade,
  author_id uuid default auth.uid() references public.profiles (id) on delete set null,
  body text not null check (char_length(btrim(body)) between 1 and 4000),
  quote text not null default '' check (char_length(quote) <= 500),
  created_at timestamptz not null default now(),
  resolved boolean not null default false,
  resolved_at timestamptz,
  resolved_by uuid references public.profiles (id) on delete set null
);

create index comments_doc_idx on public.comments (doc_id);

create table public.comment_replies (
  id uuid primary key default gen_random_uuid(),
  comment_id text not null references public.comments (id) on delete cascade,
  author_id uuid default auth.uid() references public.profiles (id) on delete set null,
  body text not null check (char_length(btrim(body)) between 1 and 4000),
  created_at timestamptz not null default now()
);

create index comment_replies_comment_idx on public.comment_replies (comment_id);

-- Resolving records who and when; the app only sends `resolved`.
create function public.stamp_comment_resolution() returns trigger
language plpgsql set search_path = public as $$
begin
  if new.resolved is distinct from old.resolved then
    new.resolved_at := case when new.resolved then now() end;
    new.resolved_by := case when new.resolved then auth.uid() end;
  end if;
  return new;
end $$;

create trigger comments_stamp_resolution
  before update of resolved on public.comments
  for each row execute function public.stamp_comment_resolution();

-- A reply reopens a resolved thread.
create function public.reopen_on_reply() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.comments set resolved = false where id = new.comment_id and resolved;
  return new;
end $$;

create trigger comment_replies_reopen
  after insert on public.comment_replies
  for each row execute function public.reopen_on_reply();

-- ------------------------------------------------------------------- roles

-- The signed-in person's role on a document: owner, editor, commenter, viewer, or null.
create function public.doc_role(p_doc uuid) returns text
language sql stable security definer set search_path = public as $$
  select case
    when d.owner_id = auth.uid() then 'owner'
    else (select s.role from public.document_shares s where s.doc_id = d.id and s.user_id = auth.uid())
  end
  from public.documents d
  where d.id = p_doc
$$;

create function public.role_rank(p_role text) returns integer
language sql immutable as $$
  select case p_role when 'owner' then 4 when 'editor' then 3 when 'commenter' then 2 when 'viewer' then 1 else 0 end
$$;

create function public.has_doc_role(p_doc uuid, p_needed text) returns boolean
language sql stable security definer set search_path = public as $$
  select public.role_rank(public.doc_role(p_doc)) >= public.role_rank(p_needed)
$$;

-- For clear messages when a document cannot be opened: the role, 'none' (exists, no access) or 'missing'.
create function public.check_document_access(p_doc uuid) returns text
language sql stable security definer set search_path = public as $$
  select case
    when not exists (select 1 from public.documents where id = p_doc) then 'missing'
    else coalesce(public.doc_role(p_doc), 'none')
  end
$$;

-- Turns a storage folder name into a document id, or null.
create function public.try_uuid(p_text text) returns uuid
language plpgsql immutable as $$
begin
  return p_text::uuid;
exception when invalid_text_representation then
  return null;
end $$;

-- ------------------------------------------------------------- saving text

-- The document with comment anchors removed and unset attributes dropped, so two
-- versions compare equal when they differ only in comments. Mirrors
-- sameIgnoringComments() in src/api/content.ts. (jsonb ignores key order already.)
create function public.canonical_doc(p_node jsonb) returns jsonb
language plpgsql immutable as $$
declare
  result jsonb := p_node - 'attrs' - 'marks' - 'content';
  attrs jsonb;
  marks jsonb;
  children jsonb := '[]'::jsonb;
  child jsonb;
  prev jsonb;
begin
  if jsonb_typeof(p_node -> 'attrs') = 'object' then
    attrs := jsonb_strip_nulls(p_node -> 'attrs');
    if attrs <> '{}'::jsonb then
      result := result || jsonb_build_object('attrs', attrs);
    end if;
  end if;

  if jsonb_typeof(p_node -> 'marks') = 'array' then
    select coalesce(jsonb_agg(
             case when jsonb_typeof(m -> 'attrs') = 'object' and jsonb_strip_nulls(m -> 'attrs') <> '{}'::jsonb
               then jsonb_build_object('type', m -> 'type', 'attrs', jsonb_strip_nulls(m -> 'attrs'))
               else jsonb_build_object('type', m -> 'type')
             end order by ord), '[]'::jsonb)
      into marks
      from jsonb_array_elements(p_node -> 'marks') with ordinality as t(m, ord)
     where m ->> 'type' <> 'comment';
    if marks <> '[]'::jsonb then
      result := result || jsonb_build_object('marks', marks);
    end if;
  end if;

  if jsonb_typeof(p_node -> 'content') = 'array' then
    for child in select public.canonical_doc(c) from jsonb_array_elements(p_node -> 'content') with ordinality as t(c, ord) order by ord loop
      prev := children -> -1;
      -- Text split only by a comment anchor joins back up.
      if prev is not null and prev ->> 'type' = 'text' and child ->> 'type' = 'text'
         and (prev -> 'marks') is not distinct from (child -> 'marks') then
        children := jsonb_set(children, array[(jsonb_array_length(children) - 1)::text],
                              prev || jsonb_build_object('text', (prev ->> 'text') || (child ->> 'text')));
      else
        children := children || jsonb_build_array(child);
      end if;
    end loop;
    if children <> '[]'::jsonb then
      result := result || jsonb_build_object('content', children);
    end if;
  end if;

  return result;
end $$;

-- Saves document content. Errors use PostgREST status codes:
--   PT403 not allowed, PT404 missing, PT409 version conflict (detail = current version).
create function public.save_document(
  p_doc uuid,
  p_content jsonb,
  p_base_version integer,
  p_force boolean default false,
  p_preview jsonb default null
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  d public.documents;
  role text := public.doc_role(p_doc);
  comments_only boolean;
begin
  if auth.uid() is null then
    raise exception using errcode = 'PT401', message = 'Your session has ended. Sign in again.';
  end if;
  select * into d from public.documents where id = p_doc for update;
  if not found then
    raise exception using errcode = 'PT404', message = 'This document does not exist or was deleted.';
  end if;
  if role is null then
    raise exception using errcode = 'PT403', message = 'You need access to this document. Ask the owner to share it with you.';
  end if;
  if jsonb_typeof(p_content) <> 'object' or p_content ->> 'type' <> 'doc' then
    raise exception using errcode = 'PT400', message = 'That is not a Write document.';
  end if;

  comments_only := public.canonical_doc(d.content) = public.canonical_doc(p_content);
  if public.role_rank(role) < public.role_rank('editor') and not (role = 'commenter' and comments_only) then
    raise exception using errcode = 'PT403', message = 'You can comment on this document but not edit it.';
  end if;
  if p_base_version <> d.version and not coalesce(p_force, false) then
    raise exception using errcode = 'PT409', message = 'This document changed somewhere else.', detail = d.version::text;
  end if;

  update public.documents set
    content = p_content,
    version = d.version + 1,
    -- Comment anchors are not edits: they leave the modified time and preview alone.
    preview = case when comments_only or p_preview is null then d.preview else p_preview end,
    updated_at = case when comments_only then d.updated_at else now() end,
    updated_by = case when comments_only then d.updated_by else auth.uid() end
  where id = p_doc
  returning version, updated_at into d.version, d.updated_at;

  return jsonb_build_object('version', d.version, 'updatedAt', d.updated_at);
end $$;

-- ------------------------------------------------------------------ people

-- Finds people to share with by name or email. Never returns the caller.
create function public.search_users(q text)
returns table (id uuid, name text, email text, color text)
language sql stable security definer set search_path = public as $$
  select p.id, p.name, p.email, p.color
  from public.profiles p
  where auth.uid() is not null
    and char_length(btrim(q)) >= 2
    and p.id <> auth.uid()
    and (p.name ilike '%' || btrim(q) || '%' or p.email ilike '%' || btrim(q) || '%')
  order by (p.name ilike btrim(q) || '%' or p.email ilike btrim(q) || '%') desc, p.name
  limit 8
$$;

-- ---------------------------------------------------- row level security

alter table public.profiles enable row level security;
alter table public.documents enable row level security;
alter table public.document_shares enable row level security;
alter table public.document_opens enable row level security;
alter table public.comments enable row level security;
alter table public.comment_replies enable row level security;

-- Start from nothing and grant exactly what the app uses.
revoke all on public.profiles, public.documents, public.document_shares, public.document_opens,
  public.comments, public.comment_replies from anon, authenticated;

-- Profiles: names and emails are visible to signed-in people, since sharing finds people by both.
grant select on public.profiles to authenticated;
grant update (name, welcomed) on public.profiles to authenticated;
create policy "profiles are visible to signed-in people" on public.profiles
  for select to authenticated using (true);
create policy "people edit their own profile" on public.profiles
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- Documents: content changes only through save_document(); titles through update.
grant select, insert, delete on public.documents to authenticated;
grant update (title) on public.documents to authenticated;
create policy "read documents you can open" on public.documents
  -- owner_id is checked on the row itself so a new document can be returned from its insert.
  for select to authenticated using (owner_id = auth.uid() or public.doc_role(id) is not null);
create policy "create your own documents" on public.documents
  for insert to authenticated with check (owner_id = auth.uid() and updated_by = auth.uid() and version = 1);
create policy "editors rename" on public.documents
  for update to authenticated using (public.has_doc_role(id, 'editor')) with check (public.has_doc_role(id, 'editor'));
create policy "owners delete" on public.documents
  for delete to authenticated using (owner_id = auth.uid());

-- Shares
grant select, insert, delete on public.document_shares to authenticated;
grant update (role) on public.document_shares to authenticated;
create policy "see who has access" on public.document_shares
  for select to authenticated using (public.has_doc_role(doc_id, 'viewer'));
create policy "editors add people" on public.document_shares
  for insert to authenticated with check (
    public.has_doc_role(doc_id, 'editor')
    and added_by = auth.uid()
    and user_id <> (select d.owner_id from public.documents d where d.id = doc_id)
  );
create policy "editors change roles" on public.document_shares
  for update to authenticated using (public.has_doc_role(doc_id, 'editor')) with check (public.has_doc_role(doc_id, 'editor'));
create policy "editors remove people, anyone leaves" on public.document_shares
  for delete to authenticated using (user_id = auth.uid() or public.has_doc_role(doc_id, 'editor'));

-- Opens: each person's own rows only.
grant select, insert, update, delete on public.document_opens to authenticated;
create policy "your own open times" on public.document_opens
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid() and public.doc_role(doc_id) is not null);

-- Comments: commenters and up. Viewers do not see comments.
grant select, insert, delete on public.comments to authenticated;
grant update (resolved) on public.comments to authenticated;
create policy "commenters read comments" on public.comments
  for select to authenticated using (public.has_doc_role(doc_id, 'commenter'));
create policy "commenters comment" on public.comments
  for insert to authenticated with check (
    author_id = auth.uid() and not resolved and public.has_doc_role(doc_id, 'commenter')
  );
create policy "commenters resolve" on public.comments
  for update to authenticated using (public.has_doc_role(doc_id, 'commenter')) with check (public.has_doc_role(doc_id, 'commenter'));
create policy "authors and owners delete threads" on public.comments
  for delete to authenticated using (
    (author_id = auth.uid() and public.has_doc_role(doc_id, 'commenter')) or public.doc_role(doc_id) = 'owner'
  );

grant select, insert on public.comment_replies to authenticated;
create policy "commenters read replies" on public.comment_replies
  for select to authenticated using (
    exists (select 1 from public.comments c where c.id = comment_id and public.has_doc_role(c.doc_id, 'commenter'))
  );
create policy "commenters reply" on public.comment_replies
  for insert to authenticated with check (
    author_id = auth.uid()
    and exists (select 1 from public.comments c where c.id = comment_id and public.has_doc_role(c.doc_id, 'commenter'))
  );

-- Functions the app calls directly; everything else stays internal.
revoke execute on all functions in schema public from public, anon;
grant execute on function public.save_document(uuid, jsonb, integer, boolean, jsonb) to authenticated;
grant execute on function public.search_users(text) to authenticated;
grant execute on function public.check_document_access(uuid) to authenticated;
grant execute on function public.doc_role(uuid), public.has_doc_role(uuid, text), public.role_rank(text),
  public.try_uuid(text), public.canonical_doc(jsonb) to authenticated;

