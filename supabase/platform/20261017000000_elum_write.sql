values ('assets', 'assets', false, 15728640,
        array['image/png', 'image/jpeg', 'image/gif', 'image/webp', 'image/avif', 'image/svg+xml', 'image/bmp'])
on conflict (id) do nothing;

create policy "write assets: read with the document" on storage.objects
  for select to authenticated using (
    bucket_id = 'assets' and public.doc_role(public.try_uuid((storage.foldername(name))[1])) is not null
  );
create policy "write assets: editors upload" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'assets' and public.has_doc_role(public.try_uuid((storage.foldername(name))[1]), 'editor')
  );
create policy "write assets: owners delete" on storage.objects
  for delete to authenticated using (
    bucket_id = 'assets' and public.doc_role(public.try_uuid((storage.foldername(name))[1])) = 'owner'
  );
